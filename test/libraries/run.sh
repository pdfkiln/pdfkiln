#!/usr/bin/env bash
# Runs the test suites of the target libraries of the specification with
# the wkhtmltopdf and wkhtmltoimage found at /usr/local/bin (the path
# phpwkhtmltopdf's tests expect) and in the PATH.
#
#   test/libraries/run.sh <work dir>
#
# Versions: pdfkit 1.0.0, knp-snappy v1.7.3 (plus snappy-smoke.php, its
# suite only uses mocks), phpwkhtmltopdf 2.5.0, wicked_pdf 2.7.0 (Rails
# 7.0), imgkit 1.2.3 (Python), CakePdf 5.3.0 (plus cakepdf-smoke.php, its
# tests only build command lines), go-wkhtmltopdf v1.9.3 (Go). Prints one
# line per library; exits 1 if one fails.
set -u
here="$(cd "$(dirname "$0")" && pwd)"
work="$1"
mkdir -p "$work"
cd "$work"
failed=0
# report <name> <status> <log>: on failure, the end of the log.
report() {
  if [ "$2" = 0 ]; then echo "PASS $1"; else echo "FAIL $1"; tail -n 30 "$3" | sed 's/^/    /'; failed=1; fi
}
clone() { [ -d "$2" ] || git clone -q --depth 1 --branch "$3" "https://github.com/$1.git" "$2"; }

echo "wkhtmltopdf: $(/usr/local/bin/wkhtmltopdf --version)"
echo "wkhtmltoimage: $(/usr/local/bin/wkhtmltoimage --version)"

clone JazzCore/python-pdfkit pdfkit 1.0.0
(cd pdfkit/tests && python pdfkit-tests.py > ../../pdfkit.log 2>&1)
report "pdfkit 1.0.0 (own suite)" $? pdfkit.log

clone KnpLabs/snappy snappy v1.7.3
(cd snappy && composer install -q --no-interaction --no-progress && vendor/bin/phpunit > ../snappy.log 2>&1)
report "knp-snappy v1.7.3 (own suite)" $? snappy.log
php "$here/snappy-smoke.php" snappy/vendor/autoload.php /usr/local/bin/wkhtmltopdf > snappy-smoke.log 2>&1
report "knp-snappy v1.7.3 (snappy-smoke.php)" $? snappy-smoke.log

clone mikehaertl/phpwkhtmltopdf phpwkhtmltopdf 2.5.0
(cd phpwkhtmltopdf && composer install -q --no-interaction --no-progress && vendor/bin/phpunit --filter PdfTest > ../phpwkhtmltopdf.log 2>&1)
report "phpwkhtmltopdf 2.5.0 (own suite, PDF tests)" $? phpwkhtmltopdf.log

# Rails 7.0 predates minitest 6, which Bundler now resolves; the dummy
# application the tests load is generated by setup_and_run_tests.
clone mileszs/wicked_pdf wicked_pdf 2.7.0
(cd wicked_pdf && { cat gemfiles/7.0.gemfile; echo "gem 'minitest', '~> 5.0'"; } > gemfiles/7.0-minitest5.gemfile \
  && export BUNDLE_GEMFILE=gemfiles/7.0-minitest5.gemfile && bundle install --quiet \
  && bundle exec rake setup_and_run_tests > ../wicked_pdf.log 2>&1)
report "wicked_pdf 2.7.0 (own suite, Rails 7.0)" $? wicked_pdf.log

# Left out: the tests of xvfb (they need it, or need it absent: the runner
# has it) and those that move the program or uninstall xvfb with sudo.
# Python 3.12 dropped assertRegexpMatches, which one test still calls.
clone jarrekk/imgkit imgkit V1.2.3
(cd imgkit/tests && sed 's/assertRegexpMatches/assertRegex/' imgkit_test.py > imgkit_py312_test.py \
  && python -m pip install -q six pytest \
  && python -m pytest -q -k "not xvfb and not cmd_not_found and not no_where_which" imgkit_py312_test.py > ../../imgkit.log 2>&1)
report "imgkit 1.2.3 (own suite)" $? imgkit.log

clone FriendsOfCake/CakePdf cakepdf 5.3.0
(cd cakepdf && composer install -q --no-interaction --no-progress && vendor/bin/phpunit --filter WkHtmlToPdf > ../cakepdf.log 2>&1)
report "CakePdf 5.3.0 (own suite, WkHtmlToPdf engine)" $? cakepdf.log
php "$here/cakepdf-smoke.php" cakepdf/vendor/autoload.php /usr/local/bin/wkhtmltopdf > cakepdf-smoke.log 2>&1
report "CakePdf 5.3.0 (cakepdf-smoke.php)" $? cakepdf-smoke.log

# Its tests load third-party pages, and wkhtmltopdf 0.12.6 exits 1, as
# pdfkiln does, on a resource that fails (31 October 2026): two test pages
# load images from loremflickr.com, which answered 500, local images instead
# keep those tests on what they check; ExampleNewPDFGenerator converts a
# page of pkg.go.dev with a badge from codebeat.co, a host gone, left out.
clone SebastiaanKlippert/go-wkhtmltopdf go-wkhtmltopdf v1.9.3
(cd go-wkhtmltopdf && sed -i 's#https://loremflickr.com/[0-9/]*#data:image/gif;base64,R0lGODlhAQABAIAAAP///wAAACH5BAEAAAAALAAAAAABAAEAAAICRAEAOw==#g' testdata/*.html \
  && go test -count=1 -v -skip '^ExampleNewPDFGenerator$' . > ../go-wkhtmltopdf.log 2>&1)
report "go-wkhtmltopdf v1.9.3 (own suite)" $? go-wkhtmltopdf.log

exit $failed
